#!/usr/bin/env python3
"""Transcribe the LDPC parity-check address tables of ARIB STD-B44 v2.1
(§3.4 (2), "Appendix 1 Bit position of parity check") from the local
`pdftotext -layout` extraction into Rust source.

Usage: python3 -I tools/b44-ldpc-tables.py specs/ARIB-STD-B44-v2.1.txt \
           > crates/isdbs3-core/src/ldpc_tables.rs

Each code rate r/120 has r rows (k_ldpc = 374·r information bits in groups
of 374); every number is a parity-bit position below n − k. The script
checks both, and that every position of each table is distinct within its
row, before writing anything: a page header or a split line in the
extraction fails the check instead of corrupting a table.
"""
import re
import sys

RATES = [41, 49, 61, 73, 81, 89, 93, 97, 101, 105, 109]
N = 44880


def main(path):
    lines = open(path, encoding="utf-8").read().splitlines()
    starts = {}
    for i, l in enumerate(lines):
        m = re.search(r"In case of coding rate (\d+)/120", l)
        if m:
            starts.setdefault(int(m.group(1)), i)
    end_marker = next(i for i, l in enumerate(lines) if "An example of coding rate 81/120" in l)
    order = sorted(starts.items(), key=lambda kv: kv[1])
    tables = {}
    for j, (rate, s) in enumerate(order):
        e = order[j + 1][1] if j + 1 < len(order) else end_marker
        rows = []
        for l in lines[s + 1 : e]:
            t = l.strip()
            # keep only lines that are nothing but integers (drops page
            # numbers like "- 16 -", headers and the ordinance reference)
            if not t or not re.fullmatch(r"[0-9]+( +[0-9]+)*", t):
                continue
            nums = [int(v) for v in t.split()]
            rows.append(nums)
        k = 374 * rate
        if len(rows) != rate:
            sys.exit(f"rate {rate}/120: {len(rows)} rows, want {rate}")
        for r in rows:
            if any(v >= N - k for v in r) or len(set(r)) != len(r):
                sys.exit(f"rate {rate}/120: bad row {r}")
        tables[rate] = rows
    if sorted(tables) != RATES:
        sys.exit(f"rates found {sorted(tables)}")
    out = [
        "//! LDPC parity-check address tables of ARIB STD-B44 v2.1 §3.4 (2),",
        "//! \"Appendix 1 Bit position of parity check\", one per inner code rate",
        "//! r/120 (r rows of parity-bit positions, one row per group of 374",
        "//! information bits). Generated by `tools/b44-ldpc-tables.py` from the",
        "//! `pdftotext -layout` extraction of the standard; do not edit by hand.",
        "",
        "/// `(r, rows)` for code rate r/120.",
        "pub static TABLES: [(u32, &[&[u16]]); 11] = [",
    ]
    for rate in RATES:
        out.append(f"    ({rate}, &[")
        for r in tables[rate]:
            out.append("        &[" + ", ".join(str(v) for v in r) + "],")
        out.append("    ]),")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
